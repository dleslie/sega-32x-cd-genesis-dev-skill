def emit_ym_instrument_setup() -> bytes:
    """Emit the authentic 4-operator FM instrument configurations for channels 0..3."""
    stream = bytearray()

    def w0(r, d):
        stream.extend([0x52, r, d])

    def w1(r, d):
        stream.extend([0x53, r, d])

    # DAC disable & LFO off
    w0(0x2B, 0x00)
    w0(0x22, 0x00)

    # Key off ch 0..2, ch 3
    w0(0x28, 0x00)
    w0(0x28, 0x01)
    w0(0x28, 0x02)
    w0(0x28, 0x04)

    # Channel 0: 12-String Acoustic Steel Guitar / Lute (Left Pan 0x80)
    # Calibrated for crisp acoustic attack and clean chord damping without release bleed or DAC clipping.
    w0(0xB0, 0x34)  # Feedback 6, Alg 4
    w0(0xB4, 0x80)  # Left pan
    w0(0x30, 0x11); w0(0x38, 0x03); w0(0x34, 0x02); w0(0x3C, 0x01)  # DT/MUL
    w0(0x40, 22);   w0(0x48, 4);    w0(0x44, 28);   w0(0x4C, 4)     # TL (Carrier TL=4 provides DAC headroom)
    w0(0x50, 0x1F); w0(0x58, 0x1F); w0(0x54, 0x1F); w0(0x5C, 0x1F)  # AR (Instantaneous attack)
    w0(0x60, 14);   w0(0x68, 8);    w0(0x64, 12);   w0(0x6C, 7)     # D1R (Initial decay)
    w0(0x70, 5);    w0(0x78, 4);    w0(0x74, 5);    w0(0x7C, 3)     # D2R (Secondary decay)
    w0(0x80, 0x4A); w0(0x88, 0x3A); w0(0x84, 0x4A); w0(0x8C, 0x3A)  # D1L/RR: RR=10 (0x0A) eliminates note bleed

    # Channel 1: Acoustic Guitar Stereo Reverb / Echo (Right Pan 0x40)
    # Balanced with +12dB attenuation relative to Lead (Carrier TL=16) and matching damping rate.
    w0(0xB1, 0x34)
    w0(0xB5, 0x40)
    w0(0x31, 0x11); w0(0x39, 0x03); w0(0x35, 0x02); w0(0x3D, 0x01)
    w0(0x41, 26);   w0(0x49, 16);   w0(0x45, 32);   w0(0x4D, 16)
    w0(0x51, 0x1F); w0(0x59, 0x1F); w0(0x55, 0x1F); w0(0x5D, 0x1F)
    w0(0x61, 14);   w0(0x69, 8);    w0(0x65, 12);   w0(0x6D, 7)
    w0(0x71, 5);    w0(0x79, 4);    w0(0x75, 5);    w0(0x7D, 3)
    w0(0x81, 0x4A); w0(0x89, 0x3A); w0(0x85, 0x4A); w0(0x8D, 0x3A)

    # Channel 2: Cathedral Choir Pad / Ethereal Swell (Center Pan 0xC0)
    # Tuned with gentle sustain taper (D1L=2) and RR=8 for clean pad dissolution on chord progression.
    w0(0xB2, 0x15)  # Alg 5
    w0(0xB6, 0xC0)
    w0(0x32, 0x11); w0(0x3A, 0x21); w0(0x36, 0x02); w0(0x3E, 0x11)
    w0(0x42, 28);   w0(0x4A, 18);   w0(0x46, 24);   w0(0x4E, 18)
    w0(0x52, 16);   w0(0x5A, 14);   w0(0x56, 16);   w0(0x5E, 14)
    w0(0x62, 3);    w0(0x6A, 3);    w0(0x66, 3);    w0(0x6E, 3)
    w0(0x72, 1);    w0(0x7A, 1);    w0(0x76, 1);    w0(0x7E, 1)
    w0(0x82, 0x28); w0(0x8A, 0x28); w0(0x86, 0x28); w0(0x8E, 0x28)

    # Channel 3: Sub-Bass Pedal Drone (Port 1 Ch 0, Center Pan 0xC0)
    # Algorithm 0 warm serial modulation: modulators OP1-OP3 smoothed to remove harsh upper buzz, RR=10.
    w1(0xB0, 0x30)  # Alg 0, Feedback 6
    w1(0xB4, 0xC0)
    w1(0x30, 0x01); w1(0x38, 0x01); w1(0x34, 0x01); w1(0x3C, 0x01)
    w1(0x40, 26);   w1(0x48, 18);   w1(0x44, 14);   w1(0x4C, 18)
